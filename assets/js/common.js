// تبدیلِ اعدادِ لاتین به فارسی — برایِ هر عددی که قراره به کاربر نمایش داده بشه
function toFa(n) {
    if (n === null || n === undefined || n === '') return '';
    return String(n).replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
}
