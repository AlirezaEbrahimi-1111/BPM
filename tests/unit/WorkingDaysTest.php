<?php
/**
 * ═══════════════════════════════════════════════════════════════════
 *  تست واحد: موتور تقویم کاری و محاسبهٔ دوره‌ها
 *  محل: /tests/unit/WorkingDaysTest.php
 * ───────────────────────────────────────────────────────────────────
 *  چرا این ماژول اول تست می‌شود؟
 *    بیشترین تراکم منطق کسب‌وکار را دارد و پرریسک‌ترین بخش سامانه
 *    است. اشتباه در محاسبهٔ موعد یا دورهٔ معوقه، مستقیماً به کاربر
 *    نهایی گزارش غلط می‌دهد.
 *
 *  تاریخ‌های مرجع (تقویم میلادی ۲۰۲۶):
 *    ۱۰ ژوئیه  → جمعه   (روز غیرکاری)
 *    ۱۱ ژوئیه  → شنبه   (اولین روز کاری هفته در ایران)
 *    ۰۴ ژوئیه  → شنبه
 * ═══════════════════════════════════════════════════════════════════
 */

require_once dirname(__DIR__, 2) . '/includes/working-days-helper.php';

return [

    'name' => 'موتور تقویم کاری و محاسبهٔ دوره‌ها',

    'tests' => [

        // ═══════════════════════════════════════════════
        //  isWorkingDay
        // ═══════════════════════════════════════════════

        'جمعه روز کاری نیست' => function (Assert $a) {
            $friday = new DateTime('2026-07-10');   // جمعه
            $a->false(
                isWorkingDay($friday, []),
                'جمعه باید غیرکاری تشخیص داده شود'
            );
        },

        'شنبه روز کاری است' => function (Assert $a) {
            $saturday = new DateTime('2026-07-11'); // شنبه
            $a->true(
                isWorkingDay($saturday, []),
                'شنبه اولین روز کاری هفته در ایران است'
            );
        },

        'تعطیل رسمی روز کاری نیست' => function (Assert $a) {
            $day = new DateTime('2026-07-12');      // یکشنبه
            $holidays = ['2026-07-12' => true];     // ولی تعطیل رسمی

            $a->true(
                isWorkingDay($day, []),
                'بدون تعطیلی، یکشنبه روز کاری است'
            );
            $a->false(
                isWorkingDay($day, $holidays),
                'با ثبت تعطیلی رسمی، همان روز غیرکاری می‌شود'
            );
        },


        // ═══════════════════════════════════════════════
        //  countWorkingDaysBetween
        // ═══════════════════════════════════════════════

        'شمارش روزهای کاری، جمعه را حذف می‌کند' => function (Assert $a) {
            // بازه: ۴ تا ۱۱ ژوئیه (شامل شروع، بدون پایان) = ۷ روز
            //   ۴=شنبه ۵=یکشنبه ۶=دوشنبه ۷=سه‌شنبه ۸=چهارشنبه ۹=پنجشنبه ۱۰=جمعه
            //   → ۶ روز کاری (جمعه حذف)
            $start = new DateTime('2026-07-04');
            $end   = new DateTime('2026-07-11');

            $a->equals(
                6,
                countWorkingDaysBetween($start, $end, []),
                'از ۷ روز تقویمی، ۶ روز کاری است (جمعه کسر شد)'
            );
        },

        'شمارش روزهای کاری، تعطیل رسمی را هم حذف می‌کند' => function (Assert $a) {
            $start    = new DateTime('2026-07-04');
            $end      = new DateTime('2026-07-11');
            $holidays = ['2026-07-07' => true];   // یک تعطیلی وسط بازه

            $a->equals(
                5,
                countWorkingDaysBetween($start, $end, $holidays),
                'با یک تعطیلی رسمی، ۵ روز کاری باقی می‌ماند'
            );
        },

        'بازهٔ صفر، صفر روز کاری دارد' => function (Assert $a) {
            $d = new DateTime('2026-07-11');
            $a->equals(
                0,
                countWorkingDaysBetween($d, $d, []),
                'شروع و پایان یکسان = صفر'
            );
        },


        // ═══════════════════════════════════════════════
        //  calcOverduePeriods — کار روزانه
        // ═══════════════════════════════════════════════

        'کار روزانه: دورهٔ معوقه بر مبنای روز کاری شمرده می‌شود' => function (Assert $a) {
            $start = new DateTime('2026-07-04');
            $today = new DateTime('2026-07-11');

            // ۶ روز کاری سررسید شده، ۲ دوره انجام شده → ۴ دوره معوقه
            $a->equals(
                4,
                calcOverduePeriods('daily', $start, $today, 2, []),
                '۶ دورهٔ سررسیدشده منهای ۲ دورهٔ انجام‌شده = ۴ معوقه'
            );
        },

        'کار روزانه: تعطیلی رسمی، دورهٔ معوقه ایجاد نمی‌کند' => function (Assert $a) {
            $start    = new DateTime('2026-07-04');
            $today    = new DateTime('2026-07-11');
            $holidays = ['2026-07-07' => true];

            $a->equals(
                3,
                calcOverduePeriods('daily', $start, $today, 2, $holidays),
                'با یک تعطیلی، دورهٔ سررسیدشده ۵ می‌شود → ۵ − ۲ = ۳'
            );
        },

        'کار روزانه: انجام بیش از حد، معوقهٔ منفی نمی‌سازد' => function (Assert $a) {
            $start = new DateTime('2026-07-04');
            $today = new DateTime('2026-07-11');

            $a->equals(
                0,
                calcOverduePeriods('daily', $start, $today, 100, []),
                'تعداد معوقه هرگز منفی نمی‌شود'
            );
        },

        'کار روزانه: پیش از تاریخ شروع، معوقه ندارد' => function (Assert $a) {
            $start = new DateTime('2026-08-01');
            $today = new DateTime('2026-07-11');   // هنوز شروع نشده

            $a->equals(
                0,
                calcOverduePeriods('daily', $start, $today, 0, []),
                'کاری که هنوز شروع نشده، معوقه ندارد'
            );
        },


        // ═══════════════════════════════════════════════
        //  calcOverduePeriods — هفتگی و ماهانه
        // ═══════════════════════════════════════════════

        'کار هفتگی: هر ۷ روز یک دوره' => function (Assert $a) {
            $start = new DateTime('2026-06-13');
            $today = new DateTime('2026-07-11');   // ۲۸ روز بعد = ۴ هفته

            $a->equals(
                3,
                calcOverduePeriods('weekly', $start, $today, 1, []),
                '۴ دورهٔ هفتگی منهای ۱ دورهٔ انجام‌شده = ۳'
            );
        },

        'کار ماهانه: هر ماه یک دوره' => function (Assert $a) {
            $start = new DateTime('2026-04-11');
            $today = new DateTime('2026-07-11');   // ۳ ماه بعد

            $a->equals(
                3,
                calcOverduePeriods('monthly', $start, $today, 0, []),
                '۳ ماه گذشته = ۳ دورهٔ معوقه'
            );
        },


        // ═══════════════════════════════════════════════
        //  calcPeriodicDelayWorkingDays
        // ═══════════════════════════════════════════════

        'تأخیر کار مقطعی بر مبنای روز کاری محاسبه می‌شود' => function (Assert $a) {
            // موعد ۴ ژوئیه، امروز ۱۱ ژوئیه
            // روزهای بعد از موعد: ۵،۶،۷،۸،۹،۱۰،۱۱ = ۷ روز
            // ۱۰ ژوئیه جمعه است → ۶ روز کاری تأخیر
            $a->equals(
                6,
                calcPeriodicDelayWorkingDays('2026-07-04', '2026-07-11', []),
                'از ۷ روز تقویمی تأخیر، ۶ روز کاری است'
            );
        },

        'کار سررسیدنشده، تأخیر ندارد' => function (Assert $a) {
            $a->equals(
                0,
                calcPeriodicDelayWorkingDays('2026-08-01', '2026-07-11', []),
                'موعدی که نرسیده، تأخیر صفر دارد'
            );
        },

        'کار دقیقاً در موعد، تأخیر ندارد' => function (Assert $a) {
            $a->equals(
                0,
                calcPeriodicDelayWorkingDays('2026-07-11', '2026-07-11', []),
                'انجام در روز موعد = بدون تأخیر'
            );
        },

    ],
];
