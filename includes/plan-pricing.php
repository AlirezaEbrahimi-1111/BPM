// تعدادِ کاربر → مدت (ماه) → قیمت (تومان) — فقط پلنِ طلایی
const PLAN_PRICING_GOLD = [
    5  => [1 => 3700000,  6 => 15000000, 12 => 24000000],
    10 => [1 => 5600000,  6 => 24000000, 12 => 38000000],
    20 => [1 => 10000000, 6 => 39000000, 12 => 62000000],
    40 => [1 => 16500000, 6 => 66000000, 12 => 105000000],
];

// مدت (ماه) → قیمت (تومان) — پلنِ نقره‌ای تعدادِ کاربر ندارد
const PLAN_PRICING_SILVER = [1 => 200000, 6 => 1000000, 12 => 2100000];

/**
 * قیمتِ یک خرید را حساب می‌کند (تومان)، یا null اگر ترکیبِ
 * plan/planUsers/months نامعتبر باشد.
 */
function planPurchasePrice(string $plan, ?int $planUsers, int $months): ?int
{
    if ($plan === 'gold') {
        if ($planUsers === null || !isset(PLAN_PRICING_GOLD[$planUsers])) return null;
        return PLAN_PRICING_GOLD[$planUsers][$months] ?? null;
    }
    if ($plan === 'silver') {
        return PLAN_PRICING_SILVER[$months] ?? null;
    }
    return null;
}

/**
 * برایِ پلنِ نقره‌ای (که تعدادِ کاربرِ متفاوتی طبقِ قیمت ندارد)، سقفِ
 * کاربرِ سازمان را روی حداکثرِ (مقدارِ فعلیِ max_users سازمان، ۱۰)
 * می‌گذاریم — چون تا امروز هیچ سازمانِ نقره‌ای‌ای وجود نداشته و عددِ
 * قراردادی‌ای برایش تعریف نشده بود.
 */
function silverPlanUsersFor(int $currentMaxUsers): int
{
    return max($currentMaxUsers, 10);
}
